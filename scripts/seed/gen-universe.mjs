const ids = new Set();
for (const f of UNIVERSE) {
  if (ids.has(f.symbol)) throw new Error('duplicate ' + f.symbol);
  ids.add(f.symbol);
}
for (const f of UNIVERSE)
  if (f.proxy && !ids.has(f.proxy) && !['BIV', 'ONEQ'].includes(f.proxy))
    throw new Error(`proxy ${f.proxy} for ${f.symbol} not in universe`);
// proxies referenced but not themselves candidates get added as ETF nodes so their holdings can be fetched
for (const [symbol, name] of [
  ['BIV', 'Vanguard Intermediate-Term Bond ETF'],
  ['ONEQ', 'Fidelity Nasdaq Composite Index ETF'],
]) {
  UNIVERSE.push({
    symbol,
    name,
    kind: 'etf',
    family: symbol === 'BIV' ? V : F,
    category: 'Proxy only',
    proxyOnly: true,
  });
}

